const {chromium} = require('playwright');
const path = require('path');
const fs = require('fs');
const assert = require('assert/strict');
const base = process.env.TYNYS_BROWSER_URL || 'http://127.0.0.1:8095/futures.html';
const output = path.resolve(process.env.TYNYS_ARTIFACT_DIR || '.futures-test-output');
fs.mkdirSync(output, {recursive: true});
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || undefined,headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const errors = [], checks = [];
  try {
    const page = await browser.newPage({viewport:{width:1500,height:1150},deviceScaleFactor:1});
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(base);
    await page.waitForFunction(()=>document.querySelector('#connection').dataset.state==='online');
    await page.waitForFunction(()=>document.querySelectorAll('.scene canvas,.scene svg').length>=2);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
    checks.push('desktop layout and scene import');
    await page.locator('#reduction').fill('80');
    await page.locator('#duration').fill('4');
    // The stand may contain a report from another user or the API smoke test.
    // Explicitly set the whole scenario instead of relying on form defaults.
    await page.locator('#lead').fill('2');
    await page.locator('#recovery').fill('24');
    await page.locator('#loss').fill('2');
    await page.locator('#bess-fault').uncheck();
    await page.locator('#hard-ore').uncheck();
    await page.locator('#lull').check();
    await page.locator('#submit').click();
    await page.waitForFunction(()=>!document.querySelector('#submit').disabled && !document.querySelector('#export').disabled,{},{timeout:240000});
    const status = await page.locator('#request-status').innerText();
    assert.match(status,/завершён/);
    assert.notEqual(await page.locator('#actual-mw').innerText(),'—');
    assert.equal(await page.locator('#comparison tr').count(),8);
    checks.push('actual simulation completed and report rendered');
    await page.locator('#timeline').evaluate(el=>{el.value='3';el.dispatchEvent(new Event('input',{bubbles:true}));});
    assert.match(await page.locator('#frame-phase').innerText(),/Ограничение/);
    await page.locator('#play').click();
    await page.waitForTimeout(1100);
    await page.locator('#play').click();
    assert.notEqual(await page.locator('#timeline').inputValue(),'3');
    await page.locator('#chart-metric').selectOption('fleet_mwh');
    assert.equal(await page.locator('#chart path').count(),2);
    checks.push('timeline, playback, phase, graph selection');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await downloadPromise;
    const file = await download.path();
    const report = JSON.parse(fs.readFileSync(file,'utf8'));
    assert.equal(report.request.reduction_mw,80);
    assert.equal(report.request.lull,true);
    assert.equal(report.frames.length,30);
    checks.push('JSON export matches request');
    await page.reload();
    await page.waitForFunction(()=>!document.querySelector('#export').disabled);
    assert.equal(await page.locator('#reduction').inputValue(),'80');
    checks.push('reload restores saved result');
    await page.locator('[data-preset=longer]').click();
    assert.equal(await page.locator('#duration').inputValue(),'6');
    assert.match(await page.locator('#result-warning').innerText(),/изменены/);
    await page.locator('#reset').click();
    assert.equal(await page.locator('#duration').inputValue(),'4');
    assert.equal(await page.locator('#lull').isChecked(),false);
    checks.push('presets, reset, dirty-result warning');
    await page.route('**/ditto/api/2/**',route=>route.abort());
    await page.waitForFunction(()=>document.querySelector('#connection').dataset.state==='stale');
    assert.notEqual(await page.locator('#actual-mw').innerText(),'—');
    assert.match(await page.locator('#result-warning').innerText(),/потеряна/);
    await page.unroute('**/ditto/api/2/**');
    await page.waitForFunction(()=>document.querySelector('#connection').dataset.state==='online');
    checks.push('offline retains visibly stale report and reconnects');
    await page.locator('#boundary').click();
    await page.waitForFunction(()=>!document.querySelector('#cancel').disabled);
    await page.locator('#cancel').click();
    await page.waitForFunction(()=>!document.querySelector('#submit').disabled,{},{timeout:30000});
    assert.match(await page.locator('#request-status').innerText(),/отменён/);
    checks.push('cancel request confirmed');
    await page.locator('#boundary').click();
    await page.waitForFunction(()=>!document.querySelector('#submit').disabled && document.querySelectorAll('.boundary-cell').length===6,{},{timeout:240000});
    checks.push('six actual duration-boundary simulations');
    await page.locator('#timeline').evaluate(el=>{el.value='3';el.dispatchEvent(new Event('input',{bubbles:true}));});
    await page.locator('#chart-metric').selectOption('grid_mw');
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:path.join(output,'Tynys-Futures.png'),fullPage:true});
    const mobile = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true});
    mobile.on('pageerror',error=>errors.push(error.message));
    await mobile.goto(base);
    await mobile.waitForFunction(()=>!document.querySelector('#export').disabled);
    assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
    await mobile.screenshot({path:path.join(output,'futures-mobile.png'),fullPage:true});
    checks.push('390px mobile layout without horizontal overflow');
    const plainText = await page.locator('body').innerText();
    assert.doesNotMatch(plainText,/\bNaN\b|\bundefined\b|\bInfinity\b/);
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(output,'futures-ui-verification.json'),JSON.stringify({status:'PASS',checks,errors,reportRequest:report.request},null,2));
    console.log(JSON.stringify({status:'PASS',checks,errors}));
  } finally {await browser.close();}
})().catch(error=>{console.error(error.stack);process.exitCode=1;});
